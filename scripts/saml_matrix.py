#!/usr/bin/env python3
"""IFORA-25: write the SAML IdP interoperability matrix from a real pytest run.

    make test-backend PYTEST_ARGS="-q -p no:warnings -rA tests/test_saml.py tests/test_saml_interop_matrix.py tests/test_saml_cert_lifecycle.py tests/test_key_encryption_separation.py" > run.log
    python3 scripts/saml_matrix.py run.log > docs/project/saml-interop-matrix.md

Every row's tests are looked up in the log's PASSED/FAILED lines. A row is "Pass" only when all of its tests passed;
a test missing from the log makes the row "Not run", never "Pass". Exits 1 when any supported row is not a Pass.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
from tests import saml_matrix as M

RESULT = re.compile(r"^(PASSED|FAILED|ERROR|XFAIL|XPASS|SKIPPED)\s+(?:backend/)?tests/(\S+?::\S+?)(?:\s|$)")


def results(log: str) -> dict:
    out = {}
    for line in log.splitlines():
        m = RESULT.match(line.strip())
        if m:
            out[m.group(2).split("[")[0]] = m.group(1)  # parametrised cases fold to their function: any failure wins below
            if m.group(1) in ("FAILED", "ERROR"):
                out[m.group(2).split("[")[0]] = m.group(1)
    return out


def main(path: str) -> int:
    res = results(Path(path).read_text())
    lines = ["# Ifora SAML IdP interoperability matrix (IFORA-25)", "",
             "Generated by `scripts/saml_matrix.py` from the test log it was given; nothing here is hand-written.", ""]
    bad = 0
    total = sum(1 for _ in M.ROWS)
    lines += ["| Row | Spec | Clause | Requirement | Result | Tests |", "|---|---|---|---|---|"]
    for r in M.ROWS:
        got = [res.get(t) for t in r.tests]
        if all(g == "PASSED" for g in got):
            verdict = "Pass"
        elif any(g in ("FAILED", "ERROR") for g in got):
            verdict = "FAIL"
        else:
            verdict = "Not run"
        if verdict != "Pass":
            bad += 1
        names = "<br>".join(f"`{t}` ({g or 'not in log'})" for t, g in zip(r.tests, got))
        lines.append(f"| {r.id} | {r.spec} | {r.clause} | {r.requirement} | {verdict} | {names} |")
    lines += ["", f"Rows: {total}. Pass: {total - bad}. Not pass: {bad}.", ""]
    lines += ["## Not built (sizing only; no implementation in IFORA-25)", "",
              "| Feature | Rough size | Risks | Proposed follow-up |", "|---|---|---|---|",
              "| SAML SP / inbound federation | L (3-4 weeks) | trust of upstream metadata and certs, account linking and JIT provisioning, assertion validation is the highest-risk code in the product, per-tenant IdP config UI | story: inbound SAML connections (validate with python3-saml; reuse this matrix in reverse) |",
              "| Single Logout (SLO) | M (1-2 weeks) | session fan-out to SPs, front-channel reliability, signed LogoutRequest handling, partial-failure UX | story: SP-initiated SLO over HTTP-Redirect first, then IdP-initiated |", ""]
    print("\n".join(lines))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1]))
