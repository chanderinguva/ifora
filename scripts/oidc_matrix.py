#!/usr/bin/env python3
"""IFORA-24: write the OIDC conformance matrix from a real pytest run.

    make test-backend PYTEST_ARGS="-q -p no:warnings -rA tests/test_oidc_*.py tests/adversarial/test_oidc_attacks.py" > run.log
    python3 scripts/oidc_matrix.py run.log > docs/project/oidc-conformance-matrix.md

Every row's tests are looked up in the log's PASSED/FAILED lines. A row is "Pass" only when all of its tests passed;
a test missing from the log makes the row "Not run", never "Pass". Exits 1 when any supported row is not a Pass.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
from tests import oidc_matrix as M  # noqa: E402

RESULT = re.compile(r"^(PASSED|FAILED|ERROR|XFAIL|XPASS|SKIPPED)\s+(?:backend/)?tests/(\S+?::\S+?)(?:\s|$)")


def results(log: str) -> dict:
    out = {}
    for line in log.splitlines():
        m = RESULT.match(line.strip())
        if m:
            out[m.group(2).split("[")[0]] = m.group(1)  # parametrised cases fold to their function: any failure wins below
            if m.group(1) in ("FAILED", "ERROR"):
                out[m.group(2).split("[")[0]] = m.group(1)
    return out


def main(path: str) -> int:
    res = results(Path(path).read_text())
    lines = ["# Ifora OIDC / OAuth conformance matrix (IFORA-24)", "",
             "Generated by `scripts/oidc_matrix.py` from the test log it was given; nothing here is hand-written.", ""]
    bad = 0
    total = sum(1 for _ in M.ROWS)
    lines += ["| Row | Spec | Clause | Requirement | Status | Result | Tests |", "|---|---|---|---|---|---|---|"]
    for r in M.ROWS:
        got = [res.get(t) for t in r.tests]
        if all(g == "PASSED" for g in got):
            verdict = "Pass"
        elif any(g in ("FAILED", "ERROR") for g in got):
            verdict = "FAIL"
        else:
            verdict = "Not run"
        if verdict != "Pass":
            bad += 1
        names = "<br>".join(f"`{t}` ({g or 'not in log'})" for t, g in zip(r.tests, got))
        lines.append(f"| {r.id} | {r.spec} | {r.clause} | {r.requirement} | {r.status} | {verdict} | {names} |")
    passed = total - bad
    lines += ["", f"Rows: {total}. Pass: {passed}. Not pass: {bad}.", ""]
    lines += ["## Not built (non-goals, recorded for later)", "",
              "| Feature | Rough size | Why not now |", "|---|---|---|",
              "| Device authorization (RFC 8628) | M | no input-constrained clients yet |",
              "| Pushed authorization requests (RFC 9126) | M | needs a request store and client policy |",
              "| Dynamic client registration (RFC 7591) | L | registration policy and abuse controls first |",
              "| DPoP (RFC 9449) | L | proof replay store and per-token binding across introspection |",
              "| CIBA | L | needs an authentication-device channel |",
              "| Token exchange (RFC 8693) | M | no delegation use case yet |",
              "| Back-channel logout | M | needs a notification queue; today logout ends that client's refresh tokens only |",
              "| Per-resource audience for user tokens | S-M | user tokens carry `aud` = issuer; service clients already select audiences |", ""]
    print("\n".join(lines))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1]))
